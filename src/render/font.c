static const unsigned char *glyph_for(char c) {
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    unsigned char u = (unsigned char)c;
    return u < GLYPH_TABLE ? glyphs[u] : glyphs[0]; /* unlisted rows are all zero: blank */
}

static void put_block(Framebuffer *fb, int x, int y, int scale, uint32_t color) {
    for (int dy = 0; dy < scale; dy++) {
        for (int dx = 0; dx < scale; dx++) {
            int px = x + dx;
            int py = y + dy;
            if (px >= 0 && px < SCREEN_W && py >= 0 && py < SCREEN_H) {
                fb->pixels[py * SCREEN_W + px] = color;
            }
        }
    }
}

int font_width(const char *text, int scale) {
    int n = (int)strlen(text);
    return n > 0 ? (n * (FONT_COLS + FONT_GAP) - FONT_GAP) * scale : 0;
}

void font_draw(Framebuffer *fb, const char *text, int x, int y, int scale, uint32_t color) {
    for (const char *c = text; *c; c++) {
        const unsigned char *rows = glyph_for(*c);
        for (int row = 0; row < FONT_ROWS; row++) {
            for (int col = 0; col < FONT_COLS; col++) {
                if (rows[row] & (1u << (FONT_COLS - 1 - col))) {
                    put_block(fb, x + col * scale, y + row * scale, scale, color);
                }
            }
        }
        x += (FONT_COLS + FONT_GAP) * scale;
    }
}
